// Cs2Js - translate the generated C# SWMM6 engine (cs/gen) into one JavaScript module (js/gen/engine.js), using
// Roslyn's semantic model. It is a copy of the TypeScript translator (Cs2Ts.cs, TsTypes.cs, TsFn.cs; mapping in TS.md)
// that writes no types: every expression and statement is the TypeScript translator's, and only declarations
// change (JS.md lists each). The helpers the output calls are named in js/cs2js_runtime.txt and specified in
// ts/RUNTIME_HELPERS.md (the JavaScript runtime, js/src/cpp, is the TypeScript runtime without its types).
//
//   dotnet bin/cs2js.dll CS_DIR JS_GEN_DIR
//
// Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and js/README.md.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

public sealed class Todo : Exception { public Todo(string m) : base(m) { } }

public static partial class Cs2Js
{
    static CSharpCompilation comp = null!;
    static readonly Dictionary<SyntaxTree, SemanticModel> models = new();
    static SemanticModel M(SyntaxNode n) => models[n.SyntaxTree];
    static readonly SortedDictionary<string, int> todos = new();
    static readonly SortedDictionary<string, string> manifest = new();   // runtime member used -> its JavaScript name
    static readonly SortedDictionary<string, int> notes = new();         // facts worth knowing that are not TODOs

    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        // the engine: the generated C#, and the hand-written engine parts kept with the runtime (Hand_*.cs)
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();
        var rt = trees.Where(t => !gen.Contains(t)).ToList();

        Directory.CreateDirectory(outDir);
        CollectTypes(gen);
        foreach (var g in engineTypes.GroupBy(TypeIdent).Where(g => g.Count() > 1)) Todo0("two types named " + g.Key);
        FindTypeDependent(rt);
        Analyze(gen);
        CollectFieldNames();
        CheckDuckTyping();

        var body = new StringBuilder();
        // enums and delegate types first: they depend on nothing
        foreach (var s in engineTypes.Where(t => t.TypeKind == TypeKind.Enum)) EnumDecl(s, body);
        body.Append('\n');
        foreach (var s in engineTypes.Where(t => t.TypeKind == TypeKind.Delegate)) DelegateDecl(s, body);
        body.Append('\n');
        // classes, every base class before its derived classes (an ES class is not hoisted)
        foreach (var s in ClassOrder())
        {
            var sb = new StringBuilder();
            try { ClassDecl(s, sb); }
            catch (Todo e) { sb.Append("// TODO ").Append(e.Message).Append('\n'); }
            body.Append(sb);
        }
        var tail = StaticInitSection();

        var o = new StringBuilder();
        o.Append("// Code generated by tools/cs2x/Cs2Js.cs from cs/gen (the C# SWMM6 engine). DO NOT EDIT.\n");
        o.Append("// Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and js/README.md.\n");
        o.Append("// Every runtime name it uses is listed in js/cs2js_runtime.txt; ts/RUNTIME_HELPERS.md specifies the helpers.\n/* eslint-disable */\n\n");
        o.Append("import * as cpp from '../src/cpp/index.js';\n\n");
        if (moduleConsts.Count > 0)
        {
            o.Append("// constants the engine needs as values with exact bits, and lambdas whose identity C# keeps\n");
            foreach (var c in moduleConsts) o.Append(c).Append('\n');
            o.Append('\n');
        }
        o.Append(body);
        o.Append(tail);
        File.WriteAllText(Path.Combine(outDir, "engine.js"), o.ToString());

        var jsDir = Path.GetFullPath(Path.Combine(outDir, ".."));
        using (var w = new StreamWriter(Path.Combine(jsDir, "cs2js_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value).ThenBy(kv => kv.Key, StringComparer.Ordinal)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(jsDir, "cs2js_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine(kv.Key + "\t" + kv.Value);
        using (var w = new StreamWriter(Path.Combine(jsDir, "cs2js_notes.txt")))
            foreach (var kv in notes.OrderByDescending(kv => kv.Value).ThenBy(kv => kv.Key, StringComparer.Ordinal)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        Console.WriteLine("wrote engine.js (" + o.Length / 1024 + " KB), " + engineTypes.Count + " types, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites, " + manifest.Count + " runtime names");
        return 0;
    }

    /// <summary>A fact about the translation that the gate should know but that is not a missing translation.</summary>
    static void Note(string what) { notes[what] = notes.TryGetValue(what, out var c) ? c + 1 : 1; }

    /// <summary>An untranslated construct, counted without stopping the translation of the member.</summary>
    static void Todo0(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1;
        throw new Todo(what);
    }

    static void Use(string key, string js) { manifest[key] = js; }

    /// <summary>Module-level constants (NaNs with exact bits, lambdas whose identity matters), emitted before the classes.</summary>
    static readonly List<string> moduleConsts = new();
    static readonly Dictionary<string, string> moduleConstByText = new();

    static string ModuleConst(string prefix, string text)
    {
        if (moduleConstByText.TryGetValue(text, out var n)) return n;
        n = "$" + prefix + (moduleConsts.Count + 1);
        moduleConsts.Add("const " + n + " = " + text + ";");
        moduleConstByText[text] = n;
        return n;
    }

    // ------------------------------------------------------------------------------------------------ names
    /// <summary>Words that cannot name a variable in a strict-mode ES module, and TypeScript's own type words (kept, so
    /// that every name is the TypeScript engine's: JavaScript allows the type words, and renaming them costs nothing).</summary>
    static readonly HashSet<string> JsReserved = new()
    {
        "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
        "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
        "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
        "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "arguments",
        "eval", "undefined", "NaN", "Infinity", "async", "of", "get", "set", "type", "declare", "namespace", "module",
        "abstract", "readonly", "as", "is", "keyof", "infer", "never", "unknown", "any", "number", "string", "boolean",
        "bigint", "symbol", "object", "require", "global", "constructor",
    };

    /// <summary>The global names the generated code uses, which no engine type or local may shadow.</summary>
    static readonly HashSet<string> JsGlobals = new()
    {
        "cpp", "Math", "Number", "BigInt", "String", "Object", "Array", "Error", "Infinity", "NaN", "undefined",
        "globalThis", "Symbol", "Boolean", "Function", "Map", "Set", "Date", "JSON", "Promise", "Reflect", "Proxy",
        "RegExp", "Float64Array", "Float32Array", "Int32Array", "Uint32Array", "Uint8Array", "Int8Array", "Int16Array",
        "Uint16Array", "BigInt64Array", "BigUint64Array", "ArrayBuffer", "DataView", "Iterable", "console", "process",
        "Record", "Partial", "Readonly",
    };

    /// <summary>Names a class member cannot take (instance) or a static member cannot take (the constructor's own).</summary>
    static readonly HashSet<string> BadMember = new()
    {
        "constructor", "__proto__", "toString", "valueOf", "hasOwnProperty", "isPrototypeOf", "propertyIsEnumerable",
        "toLocaleString", "__defineGetter__", "__defineSetter__", "__lookupGetter__", "__lookupSetter__",
    };
    static readonly HashSet<string> BadStatic = new() { "name", "length", "prototype", "caller", "arguments", "call", "apply", "bind" };

    /// <summary>A local or parameter name: JavaScript's reserved words and the module's top-level names get a trailing _.</summary>
    static string Id(string n)
    {
        n = n.TrimStart('@');
        if (n.Contains('<') || n.Contains('>')) n = n.Replace("<", "_").Replace(">", "_");
        return JsReserved.Contains(n) || JsGlobals.Contains(n) || topNames.Contains(n) ? n + "_" : n;
    }

    /// <summary>Every top-level name of the module (types), so a local never shadows one.</summary>
    static readonly HashSet<string> topNames = new();

    static bool IsRuntime(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace)
        {
            if (ns.Name == "Cpp" && ns.ContainingNamespace.IsGlobalNamespace) return true;
            ns = ns.ContainingNamespace;
        }
        return false;
    }

    static bool IsSystem(ISymbol s)
    {
        var ns = s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace) { if (ns.Name == "System" && ns.ContainingNamespace.IsGlobalNamespace) return true; ns = ns.ContainingNamespace; }
        return false;
    }

    static readonly Dictionary<ISymbol, string> typeNames = new(SymbolEqualityComparer.Default);

    /// <summary>The module-level name of an engine type: its namespace below openswmm and its class nesting, joined
    /// by _ (the Java translator's rule).</summary>
    static string TypeIdent(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (typeNames.TryGetValue(t, out var n)) return n;
        var parts = new List<string>();
        for (var c = t; c != null; c = c.ContainingType) parts.Insert(0, c.Name);
        var ns = new List<string>();
        for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
        if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global" || ns[0] == "Gen")) ns.RemoveAt(0);
        var s = string.Join("_", ns.Concat(parts));
        if (t.Name == "_F" && t.ContainingType == null)
        {
            // the free functions of a namespace: openswmm's are F_, the global namespace's F__global, others F_ns
            var full = new List<string>();
            for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) full.Insert(0, x.Name);
            s = full.Count == 1 && full[0] == "openswmm" ? "F_" : full.Count > 0 && full[0] == "openswmm" ? "F_" + string.Join("_", full.Skip(1)) : "F_" + string.Join("_", full);
        }
        if (JsReserved.Contains(s) || JsGlobals.Contains(s)) s += "_";
        typeNames[t] = s;
        return s;
    }

    static string StripArity(string s) { var i = s.IndexOf('`'); return i < 0 ? s : s.Substring(0, i); }

    /// <summary>The Go translator's parameter-type code (Cs2Go.ShortType): the runtime's overload suffixes use it.</summary>
    static string ShortType(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "i";
            case SpecialType.System_Int64: return "l";
            case SpecialType.System_UInt64: return "ul";
            case SpecialType.System_UInt32: return "u";
            case SpecialType.System_Double: return "d";
            case SpecialType.System_Single: return "f";
            case SpecialType.System_Boolean: return "b";
            case SpecialType.System_SByte: return "c";
            case SpecialType.System_Byte: return "uc";
            case SpecialType.System_Int16: return "s";
            case SpecialType.System_UInt16: return "us";
            case SpecialType.System_Object: return "o";
            case SpecialType.System_String: return "str";
        }
        if (t is IArrayTypeSymbol at) return ShortType(at.ElementType) + "A";
        if (t is ITypeParameterSymbol tp) return tp.Name;
        if (t is INamedTypeSymbol nt)
        {
            var s = nt.Name;
            if (nt.TypeArguments.Length > 0) s += string.Join("", nt.TypeArguments.Select(ShortType));
            return s;
        }
        return "x";
    }

    /// <summary>The code of a type argument in a specialisation suffix: a number or bool type (an enum by its underlying
    /// type) by its ShortType code, anything else O.</summary>
    static string SpecCode(ITypeSymbol t)
    {
        if (t.TypeKind == TypeKind.Enum && t is INamedTypeSymbol e) t = e.EnumUnderlyingType!;
        if (t.SpecialType == SpecialType.System_Char) return "ch";
        if (IsNumeric(t) || t.SpecialType == SpecialType.System_Boolean) return ShortType(t);
        return "O";
    }

    // ------------------------------------------------------------------------------------------------ members
    static readonly Dictionary<IMethodSymbol, string> methodNames = new(SymbolEqualityComparer.Default);

    /// <summary>A method whose name the runtime calls by duck typing: it implements a member of a runtime or system
    /// interface (ICopy.Clone, IDisposable.Dispose, IHashFn.HashOf, IBinFn.Call2, IComparable.CompareTo, ...) or
    /// overrides a member of System.Object (Equals, GetHashCode, ToString).</summary>
    static bool Pinned(IMethodSymbol m)
    {
        if (m.IsStatic) return false;
        for (var o = m.OverriddenMethod; o != null; o = o.OverriddenMethod) if (IsSystem(o) || IsRuntime(o)) return true;
        foreach (var i in m.ContainingType.AllInterfaces)
        {
            if (!(IsRuntime(i) || IsSystem(i))) continue;
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
                if (SymbolEqualityComparer.Default.Equals(m.ContainingType.FindImplementationForInterfaceMember(im), m)) return true;
        }
        return false;
    }

    static IEnumerable<INamedTypeSymbol> Ancestors(INamedTypeSymbol t)
    {
        for (var b = t.BaseType; b != null && !IsSystem(b); b = b.BaseType) yield return b.OriginalDefinition;
    }

    static readonly Dictionary<INamedTypeSymbol, List<INamedTypeSymbol>> descendants = new(SymbolEqualityComparer.Default);

    static List<INamedTypeSymbol> Descendants(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (descendants.TryGetValue(t, out var l)) return l;
        l = engineTypes.Where(d => Derives(d, t)).ToList();
        descendants[t] = l;
        return l;
    }

    /// <summary>The classes whose instances can hold a member of t: t, its bases and the classes derived from it.</summary>
    static IEnumerable<INamedTypeSymbol> Family(INamedTypeSymbol t) => new[] { t.OriginalDefinition }.Concat(Ancestors(t)).Concat(Descendants(t));

    static IMethodSymbol Root(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        while (m.OverriddenMethod != null && !IsSystem(m.OverriddenMethod) && !IsRuntime(m.OverriddenMethod)) m = m.OverriddenMethod.OriginalDefinition;
        return m;
    }

    /// <summary>An engine method's JavaScript name (the TypeScript translator's). JavaScript dispatches every method on the object, and a class's
    /// fields and methods share one namespace, so: an override takes its root's name; a method that shares its C#
    /// name with another method its objects can reach (an overload, or a method of a base or derived class that it
    /// does not override) gets the parameter-type suffix the Go translator uses; if that still collides (C# hiding
    /// with the same signature) the class's name is added, so every call binds as C# binds it; a name that a field
    /// of the family also uses gets M_. A method the runtime calls by name (Pinned) keeps its C# name.</summary>
    static string MethodIdent(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        if (m.OverriddenMethod != null && !IsSystem(m.OverriddenMethod) && !IsRuntime(m.OverriddenMethod)) return MethodIdent(Root(m));
        if (methodNames.TryGetValue(m, out var n)) return n;
        var t = m.ContainingType;
        var nm = m.Name.TrimStart('@');
        if (Pinned(m)) { methodNames[m] = nm; return nm; }
        // the methods the same objects (or, for a static, the same class) can reach under the same C# name
        IEnumerable<IMethodSymbol> reach = m.IsStatic
            ? t.GetMembers(m.Name).OfType<IMethodSymbol>().Where(x => x.IsStatic && x.MethodKind == MethodKind.Ordinary)
            : Family(t).SelectMany(c => c.GetMembers(m.Name).OfType<IMethodSymbol>()).Where(x => !x.IsStatic && x.MethodKind == MethodKind.Ordinary);
        var others = reach.Select(x => x.OriginalDefinition).Where(x => !SymbolEqualityComparer.Default.Equals(Root(x), m)).Distinct<IMethodSymbol>(SymbolEqualityComparer.Default).ToList();
        string Sfx(IMethodSymbol x) => "__" + string.Join("_", x.Parameters.Select(p => ShortType(p.Type) + (p.RefKind != RefKind.None ? "r" : "")));
        if (others.Count > 0)
        {
            nm += Sfx(m);
            if (others.Any(x => !Pinned(x) && Sfx(x) == Sfx(m))) nm += "__" + TypeIdent(t);
        }
        var famFields = m.IsStatic ? (Ancestors(t).Prepend(t.OriginalDefinition).Concat(Descendants(t))).SelectMany(c => c.GetMembers().OfType<IFieldSymbol>().Where(f => f.IsStatic))
                                   : Family(t).SelectMany(c => c.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic));
        if (famFields.Any(f => FieldIdent(f) == nm) || (m.IsStatic ? BadStatic.Contains(nm) : BadMember.Contains(nm))) nm = "M_" + nm;
        methodNames[m] = nm;
        return nm;
    }

    static bool IsOverrideOf(IMethodSymbol m, IMethodSymbol b)
    {
        for (var o = m.OverriddenMethod; o != null; o = o.OverriddenMethod) if (SymbolEqualityComparer.Default.Equals(o.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static bool Derives(INamedTypeSymbol d, INamedTypeSymbol b)
    {
        for (var x = d.BaseType; x != null; x = x.BaseType) if (SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static readonly Dictionary<IFieldSymbol, string> fieldNames = new(SymbolEqualityComparer.Default);

    /// <summary>A field's JavaScript name (the TypeScript translator's): its C# name, unless a base class (the runtime's included) has a field of
    /// that name, which C# keeps apart and JavaScript would merge (then the class's name is added), or the name is
    /// one JavaScript gives a meaning (constructor, the constructor's name and length, an Error's message and stack).</summary>
    static string FieldIdent(IFieldSymbol f)
    {
        f = f.OriginalDefinition;
        if (fieldNames.TryGetValue(f, out var n)) return n;
        n = f.Name.TrimStart('@');
        if (IsRuntime(f) || IsSystem(f)) { fieldNames[f] = n; return n; }
        var t = f.ContainingType;
        bool hides = false;
        for (var b = t.BaseType; b != null && !IsSystem(b); b = b.BaseType)
            if (b.GetMembers(f.Name).OfType<IFieldSymbol>().Any(x => x.IsStatic == f.IsStatic)) { hides = true; break; }
        bool exc = false;
        for (var b = t.BaseType; b != null; b = b.BaseType) if (IsRuntime(b) && b.Name == "CppException" || IsSystem(b) && b.Name == "Exception") exc = true;
        if (hides) n += "__" + TypeIdent(t);
        else if (f.IsStatic ? BadStatic.Contains(n) : BadMember.Contains(n)) n += "_";
        else if (exc && (n == "message" || n == "stack" || n == "name" || n == "cause")) n += "_";
        fieldNames[f] = n;
        return n;
    }
}
